using System.Text;
using ManualIA.Api.Data;
using ManualIA.Api.Models.Entities;
using ManualIA.Api.Services;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.IdentityModel.Tokens;

var builder = WebApplication.CreateBuilder(args);

if (builder.Environment.IsDevelopment())
{
    builder.Configuration.AddJsonFile(
        "appsettings.Local.json", optional: true, reloadOnChange: true);
    // No deploy, variáveis de ambiente continuam tendo prioridade sobre o arquivo local.
    builder.Configuration.AddEnvironmentVariables();
}

var chaveJwt = builder.Configuration["Jwt:Chave"]
    ?? throw new InvalidOperationException("A chave JWT não foi configurada.");

builder.Services.AddControllers();
builder.Services.AddDbContext<AppDbContext>(opcoes =>
    opcoes.UseNpgsql(builder.Configuration.GetConnectionString("Banco")));
builder.Services.AddScoped<IPasswordHasher<Usuario>, PasswordHasher<Usuario>>();
builder.Services.AddScoped<ProcessadorDocumento>();
builder.Services.AddScoped<AutenticacaoService>();
builder.Services.AddScoped<UsuarioService>();
builder.Services.AddScoped<ManualService>();
builder.Services.AddScoped<ChatService>();
builder.Services.AddHttpClient<ServicoIA>()
    .RedactLoggedHeaders(new[] { "x-goog-api-key" });
builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme)
    .AddJwtBearer(opcoes => opcoes.TokenValidationParameters = new TokenValidationParameters
    {
        ValidateIssuer = true,
        ValidateAudience = true,
        ValidateLifetime = true,
        ValidateIssuerSigningKey = true,
        ValidIssuer = builder.Configuration["Jwt:Emissor"],
        ValidAudience = builder.Configuration["Jwt:Publico"],
        IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(chaveJwt))
    });
builder.Services.AddAuthorization();
builder.Services.AddCors(opcoes => opcoes.AddDefaultPolicy(politica =>
    politica.WithOrigins("http://localhost:5173").AllowAnyHeader().AllowAnyMethod()));

var app = builder.Build();

app.UseCors();
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();

using (var escopo = app.Services.CreateScope())
{
    var banco = escopo.ServiceProvider.GetRequiredService<AppDbContext>();
    await banco.Database.EnsureCreatedAsync();
    await banco.Database.ExecuteSqlRawAsync("""
        CREATE TABLE IF NOT EXISTS "SessoesChat" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "UsuarioId" integer NOT NULL REFERENCES "Usuarios" ("Id") ON DELETE CASCADE,
            "ManualId" integer NOT NULL REFERENCES "Manuais" ("Id") ON DELETE CASCADE,
            "CriadaEm" timestamp with time zone NOT NULL,
            "AtualizadaEm" timestamp with time zone NOT NULL
        );
        CREATE TABLE IF NOT EXISTS "MensagensChat" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "SessaoChatId" integer NOT NULL REFERENCES "SessoesChat" ("Id") ON DELETE CASCADE,
            "Papel" character varying(20) NOT NULL,
            "Conteudo" character varying(4000) NOT NULL,
            "ReferenciasJson" text NULL,
            "CriadaEm" timestamp with time zone NOT NULL
        );
        CREATE INDEX IF NOT EXISTS "IX_SessoesChat_UsuarioId_AtualizadaEm"
            ON "SessoesChat" ("UsuarioId", "AtualizadaEm");
        CREATE INDEX IF NOT EXISTS "IX_SessoesChat_ManualId"
            ON "SessoesChat" ("ManualId");
        CREATE INDEX IF NOT EXISTS "IX_MensagensChat_SessaoChatId_CriadaEm"
            ON "MensagensChat" ("SessaoChatId", "CriadaEm");
        """);
    await BancoInicializador.CriarDadosIniciaisAsync(escopo.ServiceProvider);
}

app.Run();
